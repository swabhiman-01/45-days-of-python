# Python Program to demonstrate range() in for loop
for no in range(10):
    print(no, end=" ")
print("\n")

for no in range(2, 10):
    print(no, end=" ")
print("\n")

for no in range(2, 10, 2):
    print(no, end=" ")
print("\n")


for no in range(10, 0, -1):
    print(no, end=" ")
print("\n")
